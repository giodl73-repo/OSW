import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('almanac/reference-route-text.js','utf8'),context);
const text=context.window.OSWReferenceRouteText;
const contract=JSON.parse(fs.readFileSync('research/wicc-winter-reference-runtime-contract-v1.json'));
const row={...contract.query_contract.route,nominal_atlas_state_crossings:[]};
const report=contract.query_contract.atlas_report;
assert.equal(text.supportCitation(report.supporting_sources[0]),'doi:10.1029/2008JC004874');
assert.equal(text.supportCitation({citation:'Published citation',doi:'other'}),'Published citation');
assert.equal(text.supportCitation({title:'Source title',url:'https://example.org'}),'Source title');
assert.equal(text.supportCitation({url:'https://example.org'}),'https://example.org');
assert.equal(text.supportCitation({}),'Source details unavailable');
const geography=text.regionContext(row,report);
assert.equal(geography.label,'Editorial map overlap only: ');
assert.deepEqual(Array.from(geography.codes),['IND W']);
assert.equal(geography.note,'Physical current passage through atlas regions remains unresolved.');
assert.equal(row.physical_state_join_eligible,false);
assert.equal(row.nominal_atlas_state_crossings.length,0);
assert.equal(text.regionContext({},{}).label,'Atlas-region passage: unresolved.');
assert.deepEqual(Array.from(text.regionContext({nominal_atlas_state_crossings:['A','B']},{state_semantic_exclusions:[{state_code:'A'}]}).codes),['B']);
assert.equal(text.regionContext({nominal_atlas_state_crossings:['A']},{}).label,'Editorial route crosses atlas regions: ');
assert.match(text.summary(row),/1,500 km · range unknown/);
const source=fs.readFileSync('almanac/reference-routes.js','utf8');
assert.ok(source.includes('window.OSWReferenceRouteText.supportCitation(support)'));
assert.ok(source.includes('window.OSWReferenceRouteText.regionContext(row,report)'));
const html=fs.readFileSync('almanac/reference-routes.html','utf8');
assert.ok(html.includes('reference-route-text.js?v=2'));
assert.ok(html.includes('reference-routes.js?v=wicc-regional-2'));
assert.ok(html.indexOf('reference-route-text.js?v=2')<html.indexOf('reference-routes.js?v=wicc-regional-2'));
console.log('PASS: actual WICC citation and editorial overlap, unresolved physical join, old labels and exclusions, asset order');
